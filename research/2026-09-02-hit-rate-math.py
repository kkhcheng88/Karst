# -*- coding: utf-8 -*-
"""KARST-150 形狀校準算式(只做算術,不跑回測、不讀生產庫)。

兩個形狀:
  形狀 A —— 集中揸 5-10 隻、持有 2-5 年、不用槓桿:
             要達年化 30%,需要多少比例的持倉成為 2x/3x/5x/10x 贏家?
  形狀 B —— 市況/板塊切換 + 槓桿 ETF:
             槓桿的波動拖累與融資成本吃掉多少?切換要多準才補得回?

輸出:research/2026-09-02-hit-rate-math.txt
執行:PYTHONUTF8=1 python research/2026-09-02-hit-rate-math.py
"""
import io
import math
import os
import random

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                   "2026-09-02-hit-rate-math.txt")

lines = []
def p(s=""):
    lines.append(s)


# ---------------------------------------------------------------- 形狀 A
p("=" * 72)
p("形狀 A:集中揸 N 隻、持有 H 年、不用槓桿、等權")
p("=" * 72)
p("模型:一個週期內,比例 f 的持倉變成 M 倍,其餘 (1-f) 收於 L 倍。")
p("      組合倍數 = f*M + (1-f)*L,要求 = 1.30^H。")
p("      f = (1.30^H - L) / (M - L);f > 1 即『全部持倉都做到 M 倍仍然不夠』。")
p("")

for H in (3, 5, 10):
    target = 1.30 ** H
    p("--- 持有期 H = %d 年,要求組合倍數 = 1.30^%d = %.2fx ---" % (H, H, target))
    for L, ldesc in ((0.7, "輸家 -30%"), (1.0, "輸家打和"), (0.5, "輸家 -50%")):
        row = []
        for M in (2, 3, 5, 10, 30, 100):
            f = (target - L) / (M - L)
            row.append("%dx:%s" % (M, ("不可能" if f > 1 else "%.1f%%" % (f * 100))))
        p("  %s → 所需贏家比例  %s" % (ldesc, "  ".join(row)))
    # 以 8 隻倉為例,換算成「幾多隻」
    L = 0.7
    p("  以 8 隻等權倉、輸家 -30% 計,需要的贏家隻數:")
    for M in (3, 5, 10, 30):
        f = (target - L) / (M - L)
        if f > 1:
            p("    %dx 贏家:不可能(8 隻全中仍差)" % M)
        else:
            p("    %dx 贏家:%.1f 隻 / 8" % (M, f * 8))
    p("")

p("倉內基礎率(D-120,KARST-141 收案 2026-09-01):")
p("  單一美股做到 10 倍:十年 2-7%;五年 <0.3%;十年報酬中位數只有 2.3-3.3 倍。")
p("")
p("所需命中率 ÷ 基礎率(即『要比隨機揀股好幾多倍』):")
for H, base10, desc in ((5, 0.003, "五年 10 倍基礎率 0.3%"),
                        (10, 0.045, "十年 10 倍基礎率取 2-7% 中點 4.5%")):
    target = 1.30 ** H
    L = 0.7
    f = (target - L) / (10 - L)
    if f > 1:
        p("  H=%d,10x 贏家:不可能——%.2fx 的要求高於 10x 本身,"
          "即每一隻平均都要好過 10 倍股。" % (H, target))
    else:
        p("  H=%d(%s):需要 %.1f%% 命中,是基礎率的 %.0f 倍。"
          % (H, desc, f * 100, f / base10))
p("")
p("十年 30%% 的硬牆:1.30^10 = %.2fx。等權組合的十年平均倍數必須 >13.7x,"
  % (1.30 ** 10))
p("即『每一隻平均都要跑贏一隻十年十倍股』。對照十年報酬中位數 2.3-3.3 倍,"
  "差距約 4-6 倍。這不是命中率問題,是分佈本身的位置問題。")
p("")
p("較可行的讀法:十年 30% 要靠『每五年重新配置一次、每個五年週期做到 3.71x』,")
p("而不是揸死同一批十年。五年 3.71x 的要求見上表。")
p("")

# --------------------------------------------------- 形狀 A:單隻 CAGR 分佈角度
p("形狀 A 的另一個切入:每隻持倉需要的年化")
p("  等權、無輸家(全部持倉都達標)時,每隻都要 30% 年化。")
p("  容許 (1-f) 隻打和,則贏家那批的年化要求:")
for H in (5, 10):
    target = 1.30 ** H
    for f in (0.5, 0.33, 0.25):
        M = (target - (1 - f) * 1.0) / f
        cagr = M ** (1.0 / H) - 1
        p("    H=%d 年、%.0f%% 命中、其餘打和 → 贏家要 %.1fx,即年化 %.1f%%"
          % (H, f * 100, M, cagr * 100))
p("")


# ---------------------------------------------------------------- 形狀 B
p("=" * 72)
p("形狀 B:市況/板塊切換 + 槓桿 ETF")
p("=" * 72)
p("(B-1) 每日再平衡槓桿的長期報酬近似式")
p("  g(L) ≈ L*μ - L^2*σ^2/2 - (L-1)*r - fee      (連續複利,對數報酬口徑)")
p("  其中 μ=標的算術期望、σ=年化波動、r=融資利率、fee=管理費。")
p("  等價寫法:相對 L 倍『無拖累』的損失 = L*(L-1)*σ^2/2,即波動拖累。")
p("")
p("  波動拖累 L*(L-1)*σ^2/2(每年,以百分點計):")
p("      σ →      15%     20%     25%     30%     40%")
for L in (1, 2, 3):
    cells = []
    for sig in (0.15, 0.20, 0.25, 0.30, 0.40):
        drag = L * (L - 1) * sig * sig / 2
        cells.append("%7.1f" % (drag * 100))
    p("  L=%d  %s" % (L, "".join(cells)))
p("")
p("  意思:3 倍槓桿在 25%% 波動下,每年白白蝕約 %.1f 個百分點;"
  % (3 * 2 * 0.25 ** 2 / 2 * 100))
p("  再加 (L-1)*r 的融資成本 —— 利率 4.5%% 時 3 倍要付 %.1f 個百分點。"
  % ((3 - 1) * 4.5))
p("")

p("(B-2) 標的年化要幾高,3 倍槓桿才淨賺 30%?")
p("  解 g=ln(1.30)=%.4f,反推所需標的算術年化 μ:" % math.log(1.30))
tgt = math.log(1.30)
for sig in (0.20, 0.25, 0.30):
    for r in (0.02, 0.045):
        L = 3.0
        fee = 0.0095
        mu = (tgt + L * L * sig * sig / 2 + (L - 1) * r + fee) / L
        p("    σ=%.0f%%、融資 %.1f%% → 標的算術年化要 %.1f%%(對數口徑 %.1f%%)"
          % (sig * 100, r * 100, mu * 100, (mu - sig * sig / 2) * 100))
p("")

p("(B-3) 切換要幾準:兩態月度模型")
p("  設定:每月市場非升即跌;在『叫升』的月份持 3 倍槓桿,其餘持現金。")
p("  參數以納指級標的的長期月度分佈作 stylized 輸入(見報告來源節)。")
p("  升月比例 pu、升月平均 mu_up、跌月平均 mu_dn;")
p("  訊號準繩度:sens = 抓到升月的比例,spec = 避開跌月的比例。")
p("")

PU, MU_UP, MU_DN = 0.62, 0.045, -0.048   # stylized 月度參數
RF_M = 0.045 / 12
FEE_M = 0.0095 / 12


def cagr_switch(sens, spec, L=3.0, n=240, seed=7):
    """蒙地卡羅:月度兩態,訊號有 sens/spec,持 L 倍或現金。"""
    rnd = random.Random(seed)
    fin_m = (L - 1) * 0.045 / 12
    fee_m = FEE_M if L > 1 else 0.0009 / 12
    tot = 0.0
    for _ in range(n):
        up = rnd.random() < PU
        m = MU_UP if up else MU_DN
        m += rnd.gauss(0, 0.035)              # 月內離散
        if up:
            inpos = rnd.random() < sens
        else:
            inpos = rnd.random() > spec
        if inpos:
            g = math.log(max(1e-6, 1 + L * m)) - fin_m - fee_m
        else:
            g = RF_M
        tot += g
    return math.exp(tot * 12 / n) - 1


p("  蒙地卡羅(240 個月 = 20 年,單一種子,只作量級參考):")
p("      spec →     50%     60%     70%     80%     90%")
for sens in (0.50, 0.60, 0.70, 0.80, 0.90):
    cells = []
    for spec in (0.50, 0.60, 0.70, 0.80, 0.90):
        vals = [cagr_switch(sens, spec, seed=s) for s in range(30)]
        cells.append("%7.1f" % (sum(vals) / len(vals) * 100))
    p("  sens=%.0f%%  %s" % (sens * 100, "".join(cells)))
p("")
p("  同一模型下的對照:全程持 3 倍(sens=100%%、spec=0%%)= %.1f%%;"
  % (sum(cagr_switch(1.0, 0.0, seed=s) for s in range(30)) / 30 * 100))
p("  全程持標的(L=1、sens=100%%、spec=0%%)= %.1f%%。"
  % (sum(cagr_switch(1.0, 0.0, L=1.0, seed=s) for s in range(30)) / 30 * 100))
p("")
p("  讀法:表內達到或超過 30% 的格,就是這個形狀要求的『切換準繩度』。")
p("  擲毫參照(sens=50%%、spec=50%%)= %.1f%%,即無資訊時的水平。"
  % (sum(cagr_switch(0.5, 0.5, seed=s) for s in range(30)) / 30 * 100))
p("")
p("  三個必須寫明的免責:")
p("  (1) 模型假設月與月獨立,而且訊號的對錯與跌幅大小無關。真實市場的")
p("      大跌集中在連續月份,訊號通常在第一個跌月之後才轉,")
p("      所以這個表系統性高估切換的價值 —— 它是上限,不是預期。")
p("  (2) 這是 20 年平均年化,不是每年都有;")
p("  (3) 3 倍槓桿在 2000-2002、2008、2022 都試過 -70% 以上的回撤。")

with io.open(OUT, "w", encoding="utf-8") as f:
    f.write("\n".join(lines) + "\n")
print("written:", OUT)
print("\n".join(lines))
