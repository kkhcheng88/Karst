def main():
    b = pd.read_csv(f"{OUT}/籃子表.csv")
    med = b["急性窗相對大市低點%"].median()
    lo, hi = med - BAND, med + BAND

    rows = []
    for _, r in b.iterrows():
        t = r["代號"]
        lvl, grade, why = LEVELS.get(t, ("未判", "", ""))
        dd = r["急性窗相對大市低點%"]
        if lvl != "大致不適用":
            mark = "—"
        elif dd < lo:
            mark = "①候選(正選)"
        elif dd <= hi:
            mark = "①候選(貼線)"
        else:
            mark = "不入(跌幅未夠深)"
        rows.append({
            "代號": t, "公司": r["公司"], "敘事適用度": lvl, "證據等級": grade,
            "急性期相對大市低點%": dd, "全期相對大市低點%": r["全期相對大市低點%"],
            "至今相對大市%": r["至今相對大市%"], "①候選": mark,
            "衝擊時200日線": r["衝擊時200日線"], "理由": why,
        })

    df = pd.DataFrame(rows)
    order = {"高度適用": 0, "部分適用": 1, "大致不適用": 2, "資料不足": 3, "未判": 4}
    df = df.sort_values(["敘事適用度", "急性期相對大市低點%"],
                        key=lambda s: s.map(order) if s.name == "敘事適用度" else s)
    df.to_csv(f"{OUT}/適用度表.csv", index=False, encoding="utf-8-sig")

    with open(f"{OUT}/適用度表.md", "w", encoding="utf-8") as f:
        f.write("# KARST-200 敘事適用度表(三十五家)\n\n")
        f.write(f"- 判準與三條裁決見同目錄 `敘事適用度判準.md`;逐家證據見 `適用度-批一` 至 `批六`。\n")
        f.write(f"- ①候選兩條閘:適用度 = 大致不適用,且急性期跌幅深過全籃中位數 **{med:.1f}%**;"
                f"貼線帶 {lo:.1f}% 至 {hi:.1f}% 標「貼線」,入登記但不當作已過閘。\n")
        f.write("- **判級全程只用 2026-01-12 之前已公開的資料,並刻意不使用衝擊後價格表現。**\n\n")
        f.write("## 四級家數\n\n")
        for k in ("高度適用", "部分適用", "大致不適用", "資料不足"):
            n = (df["敘事適用度"] == k).sum()
            f.write(f"- **{k}**:{n} 家\n")
        f.write(f"\n①候選(正選){(df['①候選']=='①候選(正選)').sum()} 家、"
                f"貼線 {(df['①候選']=='①候選(貼線)').sum()} 家。\n\n")
        f.write(df.to_markdown(index=False))
        f.write("\n")
    print(df.to_string(index=False))
    print("\n四級家數:")
    print(df["敘事適用度"].value_counts().to_string())
    print("\n①候選:")
    print(df["①候選"].value_counts().to_string())


if __name__ == "__main__":
    main()
