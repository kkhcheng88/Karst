"""KARST-161 鏈層人手表 v2(純度版)的逐鏈定義。

用戶裁決 D-147 ③(原話):「Yes, I dont care how much you add, but the purity of the
layer is the highest priority. The company in the same layer should share the same
narrative」。

判斷每家成員只問一句:**這家公司的股價,主要跟這條鏈的共同敘事走,還是跟它自己的故事走?**
後者出隊,或另立更純的鏈。

出隊四條規則(v2 統一用這四條,逐家寫明中了哪一條):
  a 位置不同 —— 它在鏈上的位置與其餘成員不同(買方/賣方、製造/零售、持牌/輕資產)
  b 定價機制不同 —— 決定它售價的那個變數,與其餘成員不同
  c 單一資產主導 —— 股價主要由一項自有資產或一宗自有事件驅動(舊倉 ADR-0039 代表性測試)
  d 主業已轉向 —— 主要股價驅動已轉去另一條鏈(多元業務只入其股價主要跟隨的那條)

資料結構:
  CHAINS[theme] = {
     new:        本條是否 v2 新開
     src:        承接自哪條 v1 鏈(帶回 v0/v1 的 valid_from/valid_to/role/note);None = 全新
     position / story / purity_note / kw / short
     members:    [(ticker, src_theme_or_None, purity_or_None), ...]
                 src_theme 有值 = 由該 v1 鏈原樣搬過來(原欄一字不改)
                 src_theme = None = v2 新增成員
  }
  MEMBER_PURITY[(theme, ticker)] 由 members 內第三格填,無則用該鏈的 purity_default。
"""
from collections import OrderedDict

CHAINS = OrderedDict()


def C(theme, new, src, position, story, purity_note, purity_default, kw,
      members, short=""):
    CHAINS[theme] = dict(new=new, src=src, position=position, story=story,
                         purity_note=purity_note, purity_default=purity_default,
                         kw=kw, members=members, short=short)


